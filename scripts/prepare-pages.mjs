import { createHash } from 'node:crypto';
import { readFile, writeFile, copyFile, rm } from 'node:fs/promises';
const output = new URL('../dist/atlas-web/browser/', import.meta.url);
let html = await readFile(new URL('index.html', output), 'utf8');
// Keep Angular's generated stylesheet loader compatible with a CSP without inline scripts.
for (const match of [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)]) {
  const filename = 'bootstrap-' + createHash('sha256').update(match[1]).digest('hex').slice(0,16) + '.js';
  await writeFile(new URL(filename, output), match[1]);
  html = html.replace(match[0], `<script src="/${filename}"></script>`);
}
await writeFile(new URL('index.html', output), html);
await copyFile(
  new URL('../hosting/cloudflare/worker.mjs', import.meta.url),
  new URL('_worker.js', output),
);
await writeFile(
  new URL('_routes.json', output),
  JSON.stringify({ version: 1, include: ['/api', '/api/*'], exclude: [] }, null, 2) + '\n',
);
// Netlify's external proxy syntax does not apply to Pages. API routing is handled by the Worker.
await writeFile(new URL('_redirects', output), '/launcher /how-to-play 302\n/launcher/ /how-to-play 302\n');
console.log('Cloudflare Pages build prepared; API origin: api.atlascobblemon.com.br');

// Large launcher packages are split into <=20 MiB static parts. Keep generated bytes out of Git.
for (const feed of ['latest.json','windows/latest.json']) {
const launcherManifest = new URL('../public/launcher/' + feed, import.meta.url);
try {
 const {link, mkdir, stat} = await import('node:fs/promises');
 const envelope = JSON.parse(await readFile(launcherManifest, 'utf8'));
 const release = JSON.parse(Buffer.from(envelope.payload, 'base64').toString('utf8'));
 for (const part of release.parts) {
   if (!/^launcher\/files\/[0-9A-Za-z.+-]+\/[0-9]{3}\.bin$/.test(part.path)) throw new Error('Invalid launcher part path');
   const source = new URL('../.launcher-distribution/' + part.path, import.meta.url);
   const target = new URL(part.path, output);
   if ((await stat(source)).size !== part.size) throw new Error('Launcher part size mismatch');
   const actual = createHash('sha256').update(await readFile(source)).digest('hex');
   if (actual !== part.sha256) throw new Error('Launcher part hash mismatch');
   await mkdir(new URL('./', target), {recursive:true});
   try { await link(source, target); } catch (error) { if(error.code === 'EXDEV') await copyFile(source, target); else if(error.code !== 'EEXIST') throw error; }
 }
 console.log('Signed launcher distribution parts prepared for Pages.');
} catch (error) {
 if (error.code !== 'ENOENT' || error.path !== launcherManifest.pathname) throw error;
}

}
